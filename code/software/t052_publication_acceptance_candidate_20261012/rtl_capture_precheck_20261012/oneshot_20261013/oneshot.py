"""Prepare the signed T052 128-edge window; execute only with a pinned permit.

Preparation hashes files but never invokes Icarus/VVP (not even --version).
No approval is generated by this program. The old P0 sources remain immutable.
"""
import argparse
from contextlib import contextmanager
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import platform
import sys
import zipfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
DOC = ROOT / 'code/docs/test/t052_publication_acceptance_20261012'
OLD_MANIFEST = DOC / 'CONTROL_PREPARATION_20261012/P0_1_DRIVER_20261013/combination_manifest.json'
OLD_SHA = '0949f09747f517b08b36d6df78f8712111bb84f2da152b5a6969986532421b6c'
CHECKER = HERE.parent / 'successor_20261013/checker.py'
CHECKER_SHA = 'dd15c40566c30e8e3c9e2eb96c297db762daacb0984543231766fb72db87f74c'
RUNNER_DIR = ROOT / 'code/software/t052_runner_acceptance_candidate_20261012'
TRACK_FILES = {'controls': 't052_controls_actual.jsonl',
               'observations': 't052_observations_actual.jsonl',
               'publications': 't052_publications_actual.jsonl',
               'resets': 't052_reset_events_actual.jsonl'}
DESTINATIONS = {'dut': 'readonly/t052_polyphony_test_source.sv',
                'dds': 'readonly/dds_oscillator.sv',
                'mixer': 'readonly/pcm_mixer_4voice.sv',
                'rom': 'readonly/sine_1024_8192.mem',
                'tb': 'tb_t052_control_128_v2.sv',
                'observer': 't052_public_observer_v2.sv',
                'driver_mem': 'controls_128.hex'}
BUDGETS = {'total': 300, 'compile': 90, 'run': 90, 'check': 90}
SCHEMA = 'T052_128_ONESHOT_PREPARATION_V1'


def need(value, diagnostic):
    if not value:
        raise ValueError(diagnostic)


def identity(path):
    raw = Path(path).read_bytes()
    return {'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()}


def spec(path):
    path = Path(path).resolve()
    return {'path': path.as_posix(), **identity(path)}


def read(path):
    def pairs(items):
        result = {}
        for key, value in items:
            need(key not in result, 'DUPLICATE_JSON_KEY')
            result[key] = value
        return result
    return json.loads(Path(path).read_text(encoding='utf-8'),
                      object_pairs_hook=pairs,
                      parse_constant=lambda _: need(False, 'NONFINITE_JSON'))


def write(path, value):
    with Path(path).open('x', encoding='utf-8', newline='\n') as stream:
        json.dump(value, stream, indent=2, ensure_ascii=False)
        stream.write('\n')


def check_file(item):
    need(identity(item['path']) == {k: item[k] for k in ('bytes', 'sha256')},
         'FILE_IDENTITY:' + item['path'])


def import_file(name, path):
    module_spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(module)
    return module


def source_bytes(item):
    path = Path(item['path'])
    if not path.is_absolute():
        path = ROOT / path
    if 'member' in item:
        with zipfile.ZipFile(path) as archive:
            raw = archive.read(item['member'])
    else:
        raw = path.read_bytes()
    need(len(raw) == item['bytes'] and hashlib.sha256(raw).hexdigest() == item['sha256'],
         'FROZEN_SOURCE:' + str(path))
    return raw


def tool_inventory(suite):
    """Conservative static superset, NOT evidence of actual DLL loads."""
    suite = Path(suite).resolve()
    python = Path(sys.executable).resolve()
    paths = {suite / 'bin/iverilog.exe', suite / 'bin/vvp.exe', python}
    for directory in (suite / 'bin', suite / 'lib', python.parent):
        paths.update(directory.glob('*.dll'))
        paths.update(directory.glob('python*.zip'))
    for directory in (suite / 'lib/ivl', python.parent / 'DLLs', python.parent / 'Lib'):
        need(directory.is_dir(), 'DEPENDENCY_DIRECTORY_MISSING:' + str(directory))
        paths.update(p for p in directory.rglob('*') if p.is_file()
                     and not {'site-packages', '__pycache__'} & set(p.parts)
                     and p.suffix.lower() in {'.py', '.dll', '.pyd', '.exe', '.vpi',
                                              '.tgt', '.conf', '.vh', '.h'})
    result = {'compile': spec(suite / 'bin/iverilog.exe'),
              'runtime': spec(suite / 'bin/vvp.exe'), 'python': spec(python)}
    for index, path in enumerate(sorted(paths - {Path(x['path']) for x in result.values()})):
        result['dependency_%04d' % index] = spec(path)
    need(any(Path(item['path']).name == 'ivl.exe' for item in result.values()), 'IVL_MISSING')
    need(any(Path(item['path']).name == 'ivlpp.exe' for item in result.values()), 'IVLPP_MISSING')
    return result


def fixed_environment(suite, work):
    system = Path(os.environ['SystemRoot']).resolve()
    return {'SystemRoot': str(system), 'WINDIR': str(system),
            'COMSPEC': str(system / 'System32/cmd.exe'),
            'PATH': os.pathsep.join(str(x) for x in
                                   (suite / 'bin', suite / 'lib', system / 'System32')),
            'TEMP': str(work), 'TMP': str(work),
            'PYTHONHASHSEED': '0', 'PYTHONIOENCODING': 'utf-8',
            'IVERILOG_ROOT': str(suite / 'lib/ivl')}


def prepare(output, suite):
    output = Path(output).resolve()
    need(not output.exists(), 'OUTPUT_EXISTS')
    need(output.is_relative_to(ROOT / 'code/output'), 'PREPARATION_OUTPUT_SCOPE')
    need(identity(OLD_MANIFEST)['sha256'] == OLD_SHA, 'SIGNED_MANIFEST_CHANGED')
    need(identity(CHECKER)['sha256'] == CHECKER_SHA, 'SIGNED_CHECKER_CHANGED')
    original = read(OLD_MANIFEST)
    for item in [original['plan'], original['calendar'], *original['sources'].values()]:
        source_bytes(item)
    tools = tool_inventory(suite)
    manifest = json.loads(json.dumps(original))
    manifest['tools'] = tools
    manifest['compile_argv'][0] = tools['compile']['path']
    # Explicit backend directory eliminates an ambient IVL search choice.
    manifest['compile_argv'][1:1] = ['-B', str(Path(suite).resolve() / 'lib/ivl')]
    manifest['run_argv'][0] = tools['runtime']['path']
    manifest['run_argv'] = [('+TOOL_SHA=' + tools['runtime']['sha256'])
                            if item.startswith('+TOOL_SHA=') else item
                            for item in manifest['run_argv']]
    software = [HERE / 'oneshot.py', CHECKER, ROOT / original['calendar']['path'],
                RUNNER_DIR / 'runner_tail_20261013.py', RUNNER_DIR / 'runner.py',
                RUNNER_DIR / 'windows_job.py']
    inputs = {p.as_posix(): identity(p) for p in software}
    run_output = output / 'actual_once'
    output.mkdir(parents=True)
    write(output / 'manifest.json', manifest)
    config = {'schema': SCHEMA, 'execution_authorized': False,
              'machine': platform.node(), 'python_version': sys.version,
              'manifest': spec(output / 'manifest.json'),
              'signed_manifest': spec(OLD_MANIFEST),
              'software': inputs, 'budgets_seconds': BUDGETS,
              'output': str(run_output), 'marker': str(output / 'consumed.json'),
              'environment': fixed_environment(Path(suite).resolve(), run_output / 'work'),
              'calls': {'compile': 1, 'run': 1, 'check': 1, 'version_queries': 0},
              'actual_load_closure': 'UNKNOWN_UNTIL_AUTHORIZED_EXECUTION',
              'inventory_scope': 'STATIC_SUPERSET_NOT_OBSERVED_LOADS; OS loader/system DLLs not traced',
              'old_tools_equal': {name: tools[name] == original['tools'][name]
                                  for name in ('compile', 'runtime')},
              'T052_complete': False}
    write(output / 'config.json', config)
    return {'status': 'PREPARED_LOCKED', 'config': spec(output / 'config.json'),
            'manifest': config['manifest'], 'machine': config['machine'],
            'tool_files': len(tools), 'HDL_calls': 0, 'actual_receipt_created': False}


def verify(config_path, pinned_sha):
    config_path = Path(config_path).resolve()
    need(identity(config_path)['sha256'] == pinned_sha, 'CONFIG_EXTERNAL_PIN')
    config = read(config_path)
    need(config['schema'] == SCHEMA and config['execution_authorized'] is False,
         'CONFIG_NOT_PREPARATION')
    need(config['machine'] == platform.node(), 'MACHINE_IDENTITY')
    need(config['budgets_seconds'] == BUDGETS and
         all(type(value) is int for value in config['budgets_seconds'].values()), 'BUDGETS')
    need(config['calls'] == {'compile': 1, 'run': 1, 'check': 1, 'version_queries': 0}
         and all(type(value) is int for value in config['calls'].values()), 'CALLS')
    check_file(config['signed_manifest'])
    need(config['signed_manifest']['sha256'] == OLD_SHA, 'SIGNED_MANIFEST_PIN')
    for path, expected in config['software'].items():
        need(identity(path) == expected, 'SOFTWARE_IDENTITY:' + path)
    for required in (HERE / 'oneshot.py', CHECKER, RUNNER_DIR / 'runner_tail_20261013.py',
                     RUNNER_DIR / 'runner.py', RUNNER_DIR / 'windows_job.py'):
        need(required.as_posix() in config['software'], 'SOFTWARE_CLOSURE')
    check_file(config['manifest'])
    need(identity(CHECKER)['sha256'] == CHECKER_SHA, 'SIGNED_CHECKER_CHANGED')
    checker = import_file('signed_t052_checker', CHECKER)
    manifest = checker.load_manifest(config['manifest']['path'], config['manifest']['sha256'])
    original = read(OLD_MANIFEST)
    for field in ('sources', 'calendar', 'plan'):
        need(manifest[field] == original[field], 'ORIGINAL_CHANGED:' + field)
    need(Path(manifest['tools']['python']['path']).resolve() == Path(sys.executable).resolve(),
         'PYTHON_IDENTITY')
    output = Path(config['output']).resolve()
    need(output == config_path.parent / 'actual_once' and
         output.is_relative_to(ROOT / 'code/output'), 'EXECUTION_OUTPUT_SCOPE')
    need(Path(config['marker']).resolve() == config_path.parent / 'consumed.json', 'MARKER_SCOPE')
    suite = Path(manifest['tools']['compile']['path']).parents[1]
    compile_argv = list(original['compile_argv'])
    compile_argv[0] = manifest['tools']['compile']['path']
    compile_argv[1:1] = ['-B', str(suite / 'lib/ivl')]
    run_argv = list(original['run_argv'])
    run_argv[0] = manifest['tools']['runtime']['path']
    run_argv = [('+TOOL_SHA=' + manifest['tools']['runtime']['sha256'])
                if value.startswith('+TOOL_SHA=') else value for value in run_argv]
    need(manifest['compile_argv'] == compile_argv and manifest['run_argv'] == run_argv,
         'COMMAND_SCOPE')
    need(manifest['tools'] == tool_inventory(suite), 'TOOL_INVENTORY_DRIFT')
    need(config['environment'] == fixed_environment(suite, output / 'work'), 'ENVIRONMENT_DRIFT')
    need(not Path(config['marker']).exists(), 'PERMIT_ALREADY_CONSUMED')
    need(not output.exists(), 'EXECUTION_OUTPUT_EXISTS')
    return config, manifest, checker


def require_permit(approval_path, approval_sha, config_path, config):
    need(approval_path is not None and approval_sha is not None, 'M2_EXACT_PERMISSION_REQUIRED')
    need(identity(approval_path)['sha256'] == approval_sha, 'APPROVAL_EXTERNAL_PIN')
    approval = read(approval_path)
    expected = {'schema': 'T052_128_ONESHOT_APPROVAL_V1',
                'scope': 'ONE_COMPILE_ONE_128_EDGE_RUN_ONE_CHECK',
                'approved': True, 'config_sha256': identity(config_path)['sha256'],
                'machine': config['machine'], 'calls': config['calls'],
                'budgets_seconds': config['budgets_seconds'],
                'accept_static_dependency_inventory': True}
    need(json.dumps(approval, sort_keys=True) == json.dumps(expected, sort_keys=True),
         'APPROVAL_EXACT_SCOPE')


@contextmanager
def environment(values):
    saved = dict(os.environ)
    try:
        os.environ.clear()
        os.environ.update(values)
        yield
    finally:
        os.environ.clear()
        os.environ.update(saved)


def execute(config_path, config_sha, approval_path, approval_sha):
    # Check permit presence before even allocating output. No implicit approval.
    need(approval_path is not None and approval_sha is not None, 'M2_EXACT_PERMISSION_REQUIRED')
    config, manifest, checker = verify(config_path, config_sha)
    require_permit(approval_path, approval_sha, config_path, config)
    sys.path.insert(0, str(RUNNER_DIR))
    tail = import_file('t052_budget_tail', RUNNER_DIR / 'runner_tail_20261013.py')
    budget = tail.Budget(config['budgets_seconds']['total'])
    # O_EXCL single consume; failure never removes marker or retries.
    write(config['marker'], {'config_sha256': config_sha, 'approval_sha256': approval_sha,
                             'machine': platform.node(), 'attempt': 1})
    output = Path(config['output'])
    output.mkdir()
    work = output / 'work'
    receipt = {'status': 'FAIL_PARTIAL', 'exit_code': 1, 'failure': None,
               'config_sha256': config_sha, 'approval_sha256': approval_sha,
               'environment': config['environment'], 'steps': [], 'T052_complete': False}
    try:
        work.mkdir()
        snapshots = {}
        for role, item in manifest['sources'].items():
            budget.remaining(90)
            dest = work / DESTINATIONS[role]
            dest.parent.mkdir(parents=True, exist_ok=True)
            with dest.open('xb') as stream:
                stream.write(source_bytes(item))
            snapshots[role] = spec(dest)
        before_sources = {role: checker.source_identity(item)
                          for role, item in manifest['sources'].items()}
        before_tools = {role: checker.source_identity(item)
                        for role, item in manifest['tools'].items()}
        steps = {}
        with environment(config['environment']):
            for name in ('compile', 'run'):
                record = tail._run_process(output, name, manifest[name + '_argv'], work,
                                           config['budgets_seconds'][name], budget)
                receipt['steps'].append(record)
                need(record['exit_code'] == 0 and not record['timed_out'] and
                     record['launch_error'] is None, 'STEP_FAILED:' + name)
                steps[name] = {'argv': record['argv'], 'cwd': record['cwd'],
                               'exit_code': 0, 'timeout': False,
                               'stdout': spec(output / (name + '.stdout.bin')),
                               'stderr': spec(output / (name + '.stderr.bin')),
                               'executable': manifest['tools']['compile' if name == 'compile' else 'runtime']}
                budget.remaining(90)
            after_sources = {role: checker.source_identity(item)
                             for role, item in manifest['sources'].items()}
            after_tools = {role: checker.source_identity(item)
                           for role, item in manifest['tools'].items()}
            need(before_sources == after_sources and before_tools == after_tools, 'INPUT_DRIFT')
            actual = {'schema': 'T052_PUBLIC_PORT_RUN_RECEIPT_V2', 'evidence_kind': 'RTL_RUN',
                      'approval_sha256': approval_sha,
                      'manifest_sha256': config['manifest']['sha256'], 'machine': platform.node(),
                      'status': 'PASS', 'exit_code': 0, 'timeout': False,
                      'source_snapshots': snapshots, 'sources_before': before_sources,
                      'sources_after': after_sources, 'tools_before': before_tools,
                      'tools_after': after_tools, **steps,
                      'artifacts': {k: spec(work / v) for k, v in TRACK_FILES.items()}}
            # This is the raw successful tool pair, not the final stage verdict.
            actual_path = output / 'actual_run_receipt.json'
            write(actual_path, actual)
            argv = [manifest['tools']['python']['path'], '-I', '-S', '-B', '-X', 'utf8',
                    str(CHECKER), 'actual', '--manifest', config['manifest']['path'],
                    '--manifest-sha', config['manifest']['sha256'], '--plan',
                    str(ROOT / manifest['plan']['path']), '--receipt', str(actual_path),
                    '--receipt-sha', identity(actual_path)['sha256'], '--approval-sha', approval_sha]
            for key, filename in TRACK_FILES.items():
                argv.extend(['--' + key, str(work / filename)])
            record = tail._run_process(output, 'check', argv, work,
                                       config['budgets_seconds']['check'], budget)
            receipt['steps'].append(record)
            need(record['exit_code'] == 0 and not record['timed_out'] and
                 record['launch_error'] is None, 'STEP_FAILED:check')
        for path, expected in config['software'].items():
            need(identity(path) == expected, 'SOFTWARE_DRIFT')
        need(identity(config_path)['sha256'] == config_sha and
             identity(approval_path)['sha256'] == approval_sha, 'CONTROL_DRIFT')
        receipt['artifacts'] = {p.relative_to(output).as_posix(): spec(p)
                                for p in output.rglob('*') if p.is_file()}
        budget.remaining(90)
        receipt.update(status='T052_128_WINDOW_PASS', exit_code=0)
    except Exception as error:
        receipt['failure'] = type(error).__name__ + ':' + str(error)
    return tail.finalize_receipt(output / 'receipt.json', receipt, budget)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('prepare', 'verify', 'execute'))
    parser.add_argument('--output', type=Path)
    parser.add_argument('--suite', type=Path)
    parser.add_argument('--config', type=Path)
    parser.add_argument('--config-sha')
    parser.add_argument('--approval', type=Path)
    parser.add_argument('--approval-sha')
    args = parser.parse_args()
    try:
        if args.mode == 'prepare':
            result = prepare(args.output, args.suite)
        elif args.mode == 'verify':
            config, manifest, _ = verify(args.config, args.config_sha)
            result = {'status': 'VERIFIED_LOCKED', 'HDL_calls': 0,
                      'machine': config['machine'], 'tool_files': len(manifest['tools'])}
        else:
            result = execute(args.config, args.config_sha, args.approval, args.approval_sha)
    except (OSError, ValueError, KeyError, TypeError) as error:
        result = {'status': 'FAIL_LOCKED', 'exit_code': 1, 'diagnostic': str(error)}
    print(json.dumps(result, ensure_ascii=False))
    return result.get('exit_code', 0)


if __name__ == '__main__':
    raise SystemExit(main())
