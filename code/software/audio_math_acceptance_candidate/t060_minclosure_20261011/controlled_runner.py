"""Exact A/B one-shot runner. Default is identity preflight, NEVER execution.

Only a separate M2 approval bound to this config SHA enables future tools.
The approval file is not generated by preparation or software qualification.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import signal
import subprocess
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parent))
if os.name == 'nt':
    from windows_job import WindowsJob


def require(ok, diagnostic):
    if not ok:
        raise ValueError(diagnostic)


def pairs(items):
    result = {}
    for key, value in items:
        require(key not in result, 'RUNNER_DUPLICATE_KEY:' + key)
        result[key] = value
    return result


def load(path):
    return json.loads(Path(path).read_text(encoding='utf-8'), object_pairs_hook=pairs,
                      parse_constant=lambda _: require(False, 'RUNNER_NONFINITE'))


def identity(path):
    raw = Path(path).read_bytes()
    return dict(bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest())


def dump(path, value):
    with Path(path).open('x', encoding='utf-8', newline='\n') as stream:
        json.dump(value, stream, indent=2, ensure_ascii=False)
        stream.write('\n')


def member(root, name):
    path = (Path(root) / name).resolve()
    require(not Path(name).is_absolute() and path.is_relative_to(Path(root).resolve())
            and path != Path(root).resolve(), 'RUNNER_MEMBER_ESCAPE')
    require(not any(p.is_symlink() for p in (path, *path.parents)), 'RUNNER_SYMLINK')
    return path


class Budget:
    """Monotonic total budget, starting BEFORE preflight, including post-checks."""
    def __init__(self, seconds=900, clock=time.monotonic):
        require(type(seconds) in (int, float) and 0 < seconds <= 900, 'RUNNER_BUDGET')
        self.clock, self.seconds = clock, seconds
        self.started = clock()

    def limit(self, cap):
        remaining = self.seconds - (self.clock() - self.started)
        require(remaining > 0, 'RUNNER_TOTAL_TIMEOUT')
        require(0 < cap <= 300, 'RUNNER_STEP_CAP')
        return min(cap, remaining)

    def elapsed(self):
        return self.clock() - self.started


def kill_owned_tree(process, job=None):
    """Kill only the PID/tree created by this invocation, never tool-name kills."""
    if os.name == 'nt':
        require(job is not None, 'RUNNER_NO_OWNED_JOB')
        return job.terminate()
    os.killpg(process.pid, signal.SIGKILL)
    return dict(pid=process.pid, signal='SIGKILL', owned_process_group=True)


def step(out, label, argv, cwd, budget, cap, expected=0, diagnostic=None, env=None):
    timeout = budget.limit(cap)
    begin = time.monotonic()
    stdout_path, stderr_path = out / (label + '.stdout.txt'), out / (label + '.stderr.txt')
    timed_out, cleanup, code, failure = False, None, None, None
    # Files retain partial bytes even when a descendant owns inherited pipes.
    with stdout_path.open('xb') as stdout, stderr_path.open('xb') as stderr:
        job = WindowsJob() if os.name == 'nt' else None
        options = dict(creationflags=subprocess.CREATE_NEW_PROCESS_GROUP | 0x4) if job else dict(start_new_session=True)
        process = None
        try:
            try:
                process = subprocess.Popen(argv, cwd=cwd, env=env, stdout=stdout, stderr=stderr, **options)
                if job:
                    job.attach_and_resume(process)
                code = process.wait(timeout=timeout)
            except subprocess.TimeoutExpired:
                timed_out = True
                cleanup = kill_owned_tree(process, job)
                code = process.wait(timeout=5)
            except Exception as error:
                failure = 'RUNNER_LAUNCH_OR_CLEANUP_FAILED:' + str(error)
        finally:
            if job:
                job.close()  # Also stops descendants after a normal parent exit.
    raw = stdout_path.read_bytes() + stderr_path.read_bytes()
    receipt = dict(label=label, argv=list(map(str, argv)), cwd=str(cwd), pid=process.pid if process else None,
                   cap_seconds=cap, effective_timeout_seconds=timeout,
                   elapsed_seconds=time.monotonic() - begin, exit_code=code,
                   expected_exit=expected, diagnostic=diagnostic, timeout=timed_out,
                   cleanup=cleanup, cleanup_failure=failure,
                   stdout=identity(stdout_path), stderr=identity(stderr_path))
    dump(out / (label + '.receipt.json'), receipt)
    require(not failure and not timed_out and code == expected
            and (not diagnostic or diagnostic.encode() in raw), 'RUNNER_STEP_FAILED:' + label)
    budget.limit(90)  # Long cleanup/post-processing cannot turn an overrun PASS.
    return receipt


def verify_inputs(root, pins, budget):
    result = {}
    for name, expected in pins.items():
        budget.limit(90)
        result[name] = identity(member(root, name))
        require(result[name] == expected, 'RUNNER_INPUT_SHA:' + name)
    return result


def verify_tools(config, budget):
    result = {}
    for name, expected in config['tool_files'].items():
        budget.limit(90)
        path = Path(name)
        require(path.is_absolute(), 'RUNNER_TOOL_NOT_ABSOLUTE')
        result[name] = identity(path)
        require(result[name] == expected, 'RUNNER_TOOL_SHA:' + name)
    for tool in ('yosys', 'iverilog', 'vvp', 'python'):
        require(config['tools'][tool] in result, 'RUNNER_UNPINNED_TOOL:' + tool)
    require(any(name.endswith('/slang.so') for name in result), 'RUNNER_SLANG_IDENTITY')
    require(config['execution_authorized'] is False and config['groups'] == ['A', 'B']
            and config['total_seconds'] == 900, 'RUNNER_EXACT_PROFILE')
    return result


def check_approval(config_path, approval):
    require(approval is not None, 'RUNNER_EXECUTION_NOT_AUTHORIZED')
    value = load(approval)
    require(set(value) == {'authority', 'execution_authorized', 'config_sha256', 'groups', 'attempt', 'notice'}
            and value['authority'] == 'M2' and value['execution_authorized'] is True
            and value['config_sha256'] == identity(config_path)['sha256']
            and value['groups'] == ['A', 'B'] and type(value['attempt']) is int
            and value['attempt'] == 1 and type(value['notice']) is str and bool(value['notice'].strip()),
            'RUNNER_APPROVAL_NOT_EXACT')
    return value


def claim_attempt(root, config_raw, approved, out):
    # Exclusive create is atomic: second invocation fails before any tool.
    dump(root / 'ONE_SHOT_ATTEMPT.json', dict(config=config_raw, approval=approved,
         output=str(out), started_utc=time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())))


def finish(out, budget, receipt):
    """Collect identities ONCE, before deciding success; fail closed on tail time.

    Only metadata is amended after writing the primary receipt. Failure does not
    restart the traversal or rehash partial artifacts. The final metadata write
    cannot timestamp its own completion; its completion IS checked for success,
    and an overrun gets a terminal FAIL amendment with the observed overrun time.
    """
    def fail(message):
        receipt['status'], receipt['exit_code'] = 'FAIL_PARTIAL', 1
        receipt['failure'] = (receipt['failure'] + '; ' if receipt['failure'] else '') + message

    artifacts, current, complete = {}, None, False
    try:
        iterator = iter(out.rglob('*'))
        while True:
            budget.limit(90)  # Includes traversal/stat cost, not just file reads.
            try:
                path = next(iterator)
            except StopIteration:
                complete = True
                break
            current = path.relative_to(out).as_posix()
            budget.limit(90)
            if path.is_file():
                artifacts[current] = identity(path)
                budget.limit(90)  # A single SHA crossing the deadline is FAIL.
        budget.limit(90)  # Final post-collection check, including empty outputs.
    except Exception as error:
        fail('ARTIFACT_COLLECTION:' + str(error))
    receipt.update(artifacts=artifacts, artifact_collection_complete=complete,
        artifact_collection_stopped_at=None if complete else current,
        artifact_identity_passes=1, failure_cleanup_rehash=False,
        elapsed_seconds=budget.elapsed(),
        elapsed_checkpoint='AFTER_ARTIFACTS_AND_PRIMARY_RECEIPT_WRITE',
        terminal_metadata_write_completion_budget_checked=True)
    if receipt['elapsed_seconds'] >= budget.seconds:
        fail('RUNNER_TOTAL_TIMEOUT_FINALIZATION')
    primary_elapsed = receipt['elapsed_seconds']
    dump(out / 'receipt.json', receipt)
    # Include the primary serialization/write, even if it crosses the deadline.
    receipt['elapsed_seconds'] = budget.elapsed()
    receipt['primary_receipt_write_seconds'] = receipt['elapsed_seconds'] - primary_elapsed
    if receipt['elapsed_seconds'] >= budget.seconds:
        fail('RUNNER_TOTAL_TIMEOUT_RECEIPT_WRITE')

    def amend(name):
        # This run owns receipt.json. Exclusive new temporary files prevent
        # overwriting another run; replace only our own generated metadata.
        target = out / name
        dump(target, receipt)
        target.replace(out / 'receipt.json')

    amend('.receipt.final.tmp')
    elapsed = budget.elapsed()
    if elapsed >= budget.seconds:
        receipt['elapsed_seconds'] = elapsed
        receipt['elapsed_checkpoint'] = 'AFTER_TERMINAL_METADATA_WRITE_OVERRUN'
        fail('RUNNER_TOTAL_TIMEOUT_TERMINAL_WRITE')
        amend('.receipt.failure.tmp')
        # A FAIL remains FAIL regardless of time spent preserving its metadata.
        # No tools, traversal or SHA work is repeated during this amendment.
    return receipt


def run(config_path, out, approval=None):
    budget = Budget()  # Includes config/approval/preflight/copy and post-run SHA.
    config_path, out = Path(config_path).resolve(), Path(out).resolve()
    config_raw = identity(config_path)
    config = load(config_path)
    root = config_path.parent
    # Each portable config owns ONE persistent attempt marker across output dirs.
    require(not out.exists() and out != root and not out.is_relative_to(root), 'RUNNER_OUTPUT_EXISTS_OR_NESTED')
    out.mkdir(parents=True)
    before, tools_before, steps, failure, authorized = {}, {}, [], None, False
    try:
        before = verify_inputs(root, config['inputs'], budget)
        tools_before = verify_tools(config, budget)
        if approval is None:
            status = 'PRECHECK_ONLY_EXECUTION_LOCKED'
        else:
            approved = check_approval(config_path, approval)
            claim_attempt(root, config_raw, approved, out)
            authorized = True
            # Copy exact immutable portable sources, then use only this snapshot.
            snapshot = out / 'snapshot'
            snapshot.mkdir()
            for name in config['inputs']:
                target = member(snapshot, name)
                target.parent.mkdir(parents=True, exist_ok=True)
                with target.open('xb') as stream:
                    stream.write(member(root, name).read_bytes())
                budget.limit(90)
            verify_inputs(snapshot, config['inputs'], budget)
            env = os.environ.copy()
            suite = Path(config['tools']['yosys']).parent.parent
            env['PATH'] = os.pathsep.join(map(str, (suite / 'bin', suite / 'lib',
                Path(config['tools']['python']).parent, Path(os.environ.get('SystemRoot', '/')) / 'System32')))
            env.pop('PYTHONPATH', None)
            env.pop('PYTHONHOME', None)
            env['PYTHONDONTWRITEBYTECODE'] = '1'
            # Paths in legacy future_commands are DATA only. Rebuild from frozen
            # relative source list, never execute stale host absolute paths.
            for group, number in (('A', 1), ('B', 2)):
                work = snapshot / ('future_group_' + group)
                require(work.is_dir(), 'RUNNER_GROUP_MISSING')
                for artifact in ('allocator.v', group + '.vvp', 'minclosure.jsonl'):
                    require(not (work / artifact).exists(), 'RUNNER_REFUSE_ARTIFACT:' + artifact)
                tb = snapshot / config['tb_relative']
                source_paths = [work / n for n in config['compile_sources']] + [tb / 'tb_minclosure.sv']
                dump(out / ('compiled_inputs_' + group + '.json'), {
                    'inputs': {str(p): identity(p) for p in source_paths},
                    'allocator_original': identity(work / 'sources/voice_allocator_4.sv'),
                    'lowering_command': identity(work / 'lower_allocator.ys'),
                    'path_relocation': {'from': str(root), 'to': str(snapshot)},
                    'group': group})
                commands = [
                    ('lower', [config['tools']['yosys'], '-Q', '-T', '-m', str(suite / 'share/yosys/plugins/slang.so'), '-s', 'lower_allocator.ys'], 90),
                    ('compile', [config['tools']['iverilog'], '-g2012', '-I', 'include', '-I', str(tb),
                      '-s', 'tb_minclosure', '-o', group + '.vvp', *config['compile_sources'], 'allocator.v', str(tb / 'tb_minclosure.sv')], 90),
                    ('capture', [config['tools']['vvp'], group + '.vvp', '+STIMULUS=stimulus_' + group + '.txt',
                      '+END_CYCLE=' + str(config['end_cycles'][group]), '+GROUP=' + str(number), '+VELOCITY_ROM_PATH=rom/velocity_gain_rom.mem'], 300)]
                for label, argv, cap in commands:
                    steps.append(step(out, group + '_' + label, argv, work, budget, cap, env=env))
                    produced = {'lower': 'allocator.v', 'compile': group + '.vvp', 'capture': 'minclosure.jsonl'}[label]
                    require((work / produced).is_file(), 'RUNNER_MISSING_ARTIFACT:' + produced)
                    dump(out / (group + '_' + label + '.artifact.json'), {
                        'path': str(work / produced), **identity(work / produced)})
                    if label == 'lower':
                        dump(out / ('actual_compiled_sources_' + group + '.json'), {
                            'inputs': {str(p): identity(p) for p in source_paths + [work / 'allocator.v']},
                            'include_files': {str(p): identity(p) for p in (work / 'include').rglob('*') if p.is_file()},
                            'observer': identity(tb / 'observer.svh'),
                            'separate_group_build': True, 'shared_build_claim': False})
                software = snapshot / config['software_relative']
                python = [config['tools']['python'], '-I', '-S', '-B', '-X', 'utf8']
                checker = str(software / 'check_minclosure.py')
                plan = str(snapshot / ('plan_' + group + '.json'))
                capture = str(work / 'minclosure.jsonl')
                steps.append(step(out, group + '_exact_check', python + [checker, '--capture', capture, '--plan', plan], work, budget, 90, env=env))
                for kind, diagnostic in config['mutations'][group]:
                    damaged = str(work / (kind + '.jsonl'))
                    steps.append(step(out, group + '_make_' + kind, python + [str(software / 'future_mutants.py'),
                        '--capture', capture, '--output', damaged, '--kind', kind], work, budget, 90, env=env))
                    steps.append(step(out, group + '_reject_' + kind, python + [checker, '--capture', damaged, '--plan', plan],
                                      work, budget, 90, expected=1, diagnostic=diagnostic, env=env))
            verify_inputs(snapshot, config['inputs'], budget)
            status = 'EXACT_A_B_CAPTURE_AND_FOUR_REFUSALS_PASS'
    except Exception as error:
        status, failure = 'FAIL_PARTIAL', str(error)
    try:
        after = verify_inputs(root, config['inputs'], budget)
        tools_after = verify_tools(config, budget)
        require(config_raw == identity(config_path), 'RUNNER_CONFIG_DRIFT')
        budget.limit(90)
    except Exception as error:
        after, tools_after = {}, {}
        status, failure = 'FAIL_PARTIAL', (failure or '') + '; POSTCHECK:' + str(error)
    receipt = dict(status=status, exit_code=int(failure is not None), failure=failure,
        execution_authorized=authorized, config=config_raw, sources_before=before,
        sources_after=after, tools_before=tools_before, tools_after=tools_after,
        steps=steps, total_limit_seconds=900,
        cleanup_counts_toward_budget=True, automatic_retries=0,
        t060_complete=False, t061_complete=False, physical_verified=False)
    return finish(out, budget, receipt)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--approval', type=Path)
    args = parser.parse_args()
    result = run(args.config, args.output, args.approval)
    print(json.dumps(dict(status=result['status'], exit_code=result['exit_code'], failure=result['failure'])))
    raise SystemExit(result['exit_code'])
