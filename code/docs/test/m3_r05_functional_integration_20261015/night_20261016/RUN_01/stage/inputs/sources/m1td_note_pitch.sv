// -----------------------------------------------------------------------------
// m1td_note_pitch.sv
// MIDI 音符号 -> 相位步进。对应任务 T020（可综合集成骨架）的音高查表。
//
// 定位：本模块是集成骨架的**占位实现**。完整的 DDS 属于 T004（M1，rtl/audio/），
// 本模块只解决"给定音符号，算出相位累加器步进"这一件事，
// 放在 rtl/common/ 供骨架使用；T004 落地后可由 M1 替换或复用。
//
// -----------------------------------------------------------------------------
// 算法：12 项半音表 + 八度移位（不用乘法器）
// -----------------------------------------------------------------------------
//   等程律下第 n 号音的频率：
//     f(n) = 440 * 2^((n-69)/12) = f_C4 * 2^((n-60)/12)
//   把指数拆成"半音内偏移 s"与"八度偏移 o"：
//     n = 60 + 12*o + s,  s 取 0..11
//     f(n) = f_C4 * 2^(s/12) * 2^o
//   于是只需一张 12 项的表加一个移位：
//     step(n) = SEMITONE_STEP[s] << o        (o >= 0)
//     step(n) = SEMITONE_STEP[s] >> (-o)     (o <  0)
//
//   为什么不用乘法器：Gowin 的乘法器是稀缺资源（本设计还要留给
//   混音与效果器），而移位不占 DSP。代价只是表值右移时低位被截断。
//
// -----------------------------------------------------------------------------
// 精度核算（已用 Python 逐音验证，见 V0036）
// -----------------------------------------------------------------------------
//   88 键（MIDI 21..108）全部验证，**最大误差 0.0005 音分**。
//   人耳可辨阈值约 5-10 音分，故本方案精度有四个数量级余量。
//   最低音 A0(21) 需要右移 4 位，截断误差仍远低于阈值。
//
//   注：右移是"向下取整"，会给低频音带来极小的系统性偏低，
//   但 0.0005 音分远小于任何可听范围，不做舍入补偿。
//
// -----------------------------------------------------------------------------
// 表值来源（不得手改）
// -----------------------------------------------------------------------------
//   SEMITONE_STEP[s] = round(2^32 * f_C4 * 2^(s/12) / 48000)
//   f_C4 = 261.6255653 Hz
//   其中 48000 是采样率——**分母是 Fs 不是系统时钟**，
//   因为相位累加器只在 sample_tick 上推进。
//   （这条曾在 T007 上踩过坑：用 50 MHz 当分母导致音高偏低 1041 倍，
//     表现为完全没声音。见 electronic_piano_top.sv 的 TONE_STEP 注释。）
//
//   【自洽校验】s=9（A4）必须先算出 39370534，
//   这正是 T007 已验证上板发声的 440 Hz 常量。
//   若某次改动后该值变了，说明表算错了，不要上板。
// -----------------------------------------------------------------------------

`ifndef M1TD_NOTE_PITCH_SV
`define M1TD_NOTE_PITCH_SV

`timescale 1ns / 1ps

module m1td_note_pitch #(
    // 相位累加器位宽，必须与使用它的 DDS 一致（本工程 32）
    parameter int unsigned ACC_BITS = 32,
    // 采样率，用于表值语义说明；表值本身已是常量，不参与运算
    parameter int unsigned SAMPLE_RATE_HZ = 48_000
) (
    // MIDI 音符号，合法 0..127。0..20 与 109..127 超出 88 键范围，
    // 仍可计算（等程律对全部 128 个音符号有定义），只是会被移位截断。
    input  logic [6:0]              note_number,
    // 相位步进输出，直接喂给相位累加器
    output logic [ACC_BITS-1:0]     phase_step
);

    // -------------------------------------------------------------------------
    // 12 项半音基准表（基准 C4 = MIDI 60 = 261.6255653 Hz）
    // 索引 s = note_number % 12
    //
    // 【为什么是打包向量而不是数组】
    //   iverilog 不支持 unpacked array parameter，报
    //     "sorry: unpacked array parameters are not supported yet."
    //   而 GowinSynthesis 不接受 real / $sin（EX3956），表必须是预先算好的
    //   整数常量。打包向量是纯 Verilog-2001，两个工具都接受。
    //   同一约束导致 sine_table.svh 也采用打包向量，见该文件说明。
    //
    //   位序：最低 32 位是 s=0，故取值用 SEMITONE_TABLE[32*s +: 32]。
    // -------------------------------------------------------------------------
    localparam logic [32*12-1:0] SEMITONE_TABLE = {
        32'd44191930,   // s=11  B      493.8833 Hz
        32'd41711627,   // s=10  A#     466.1638 Hz
        32'd39370534,   // s= 9  A      440.0000 Hz  <- 与 T007 已验证值一致
        32'd37160835,   // s= 8  G#     415.3047 Hz
        32'd35075158,   // s= 7  G      391.9954 Hz
        32'd33106541,   // s= 6  F#     369.9944 Hz
        32'd31248413,   // s= 5  F      349.2282 Hz
        32'd29494575,   // s= 4  E      329.6276 Hz
        32'd27839171,   // s= 3  D#     311.1270 Hz
        32'd26276679,   // s= 2  D      293.6648 Hz
        32'd24801882,   // s= 1  C#     277.1826 Hz
        32'd23409859    // s= 0  C      261.6256 Hz
    };

    // -------------------------------------------------------------------------
    // 八度偏移
    //
    //   o = (note_number - 60 - s) / 12
    //   用有符号数，因为 note_number < 60 时 o 为负（需要右移）。
    //
    //   note_number 是 7 位无符号（0..127），先零扩展到 9 位再减，
    //   得到 -60..+67 的有符号范围，除以 12 后落在 -5..+5，
    //   4 位有符号即可容纳，这里用 5 位留余量。
    // -------------------------------------------------------------------------
    logic [3:0]        semitone;      // s = note_number % 12
    logic signed [7:0] octave;        // o，相对 C4 的八度偏移

    always_comb begin
        // s 取模 12
        semitone = 4'(note_number % 7'd12);

        // o = (note_number - 60 - s) / 12
        //
        // 【位宽必须显式对齐，否则会静默出错】
        //   note_number 是 7 位无符号。若直接写
        //     octave = $signed({3'b000, note_number}) - 5'sd60 - ...
        //   则左侧 10 位、右侧被提升为 10 位无符号，5'sd60 先被当成
        //   无符号 60 再做无符号减法，note_number < 60 时发生回绕，
        //   o 变成一个很大的正数，右移分支永远不会执行，低音全部错掉。
        //   iverilog 会报 "Numeric constant truncated to 5 bits" 提示这一点。
        //
        //   正确做法：先把 note_number 零扩展到 8 位有符号（正数），
        //   所有操作数与结果同宽（8 位），全程按有符号解释。
        //   8 位有符号可表示 -128..127，足够容纳 -60..+67。
        octave = $signed({1'b0, note_number}) - 8'sd60 - $signed({4'b0000, semitone});
        octave = octave / 8'sd12;
    end

    // -------------------------------------------------------------------------
    // 查表 + 移位
    //
    // 表中取 32 位，先扩展到 ACC_BITS 位再移位，避免 ACC_BITS > 32 时丢高位。
    // 左移可能溢出，但等程律下最高音 C8(108) 的步进约 3.7e8 < 2^32，
    // 故 ACC_BITS=32 时不会溢出。
    // -------------------------------------------------------------------------
    logic [ACC_BITS-1:0] base_step;
    // 移位量（无符号，非负）。左移与右移共用一个变量，
    // 避免在表达式里对信号做取反后直接位选——那种写法语法不合法。
    logic [4:0]          shift_amt;

    always_comb begin
        // 从打包向量中取出第 semitone 项（32 位），再扩展到 ACC_BITS 位
        base_step = ACC_BITS'(SEMITONE_TABLE[32*semitone +: 32]);

        if (octave >= 0) begin
            shift_amt  = octave[4:0];
            phase_step = base_step << shift_amt;
        end else begin
            // 右移：负数取绝对值后作为移位量
            // （octave 最小 -5，5 位无符号足够表示，无取反溢出）
            shift_amt  = 5'(-octave);
            phase_step = base_step >> shift_amt;
        end
    end

endmodule

`endif // M1TD_NOTE_PITCH_SV
