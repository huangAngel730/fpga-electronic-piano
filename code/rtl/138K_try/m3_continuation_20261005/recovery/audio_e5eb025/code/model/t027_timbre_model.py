#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T027 第二音色模型与波表生成器

设计目标：
- 提供第二种与正弦波有明确谐波差异的实时音色
- 复用现有 DDS 架构（1024 点波表、32 位相位累加器）
- 支持四声部独立音色选择

音色选择：
1. 正弦波（Sine）- 基础纯音，已有实现
2. 三角波（Triangle）- 柔和音色，奇次谐波衰减快

技术规格：
- 波表长度：1024 点
- 样本格式：16 位有符号（Q15）
- 相位累加：32 位无符号
- ROM 延迟：2 周期
- 音色切换：立即生效，不影响相位连续性
"""

import numpy as np
from typing import Tuple


# 波表参数
WAVETABLE_SIZE = 1024
SAMPLE_BITS = 16
SAMPLE_MAX = 8192   # 按既有冻结口径 ±8192
SAMPLE_MIN = -8192


def generate_sine_wavetable() -> np.ndarray:
    """生成正弦波波表（按冻结口径 ±8192）

    Returns:
        1024 点 int16 数组，范围 [-8192, 8192]
    """
    t = np.arange(WAVETABLE_SIZE) / WAVETABLE_SIZE
    wave = np.sin(2 * np.pi * t)

    # 量化到 ±8192
    quantized = np.round(wave * SAMPLE_MAX).astype(np.int16)

    # 确保关键点精确
    quantized[0] = 0
    quantized[WAVETABLE_SIZE // 4] = SAMPLE_MAX       # π/2 = 8192
    quantized[WAVETABLE_SIZE // 2] = 0                # π = 0
    quantized[3 * WAVETABLE_SIZE // 4] = SAMPLE_MIN   # 3π/2 = -8192

    return quantized


def generate_triangle_wavetable() -> np.ndarray:
    """生成三角波波表（按冻结口径 ±8192）

    三角波特性：
    - 奇次谐波：1/n² 衰减
    - 听感柔和，适合钢琴类音色
    - 波形对称，THD 低于方波

    Returns:
        1024 点 int16 数组，范围 [-8192, 8192]
    """
    wave = np.zeros(WAVETABLE_SIZE)

    # 第一季度：0 → +1
    quarter = WAVETABLE_SIZE // 4
    wave[0:quarter] = np.linspace(0, 1, quarter, endpoint=False)

    # 第二季度：+1 → 0
    wave[quarter:2*quarter] = np.linspace(1, 0, quarter, endpoint=False)

    # 第三季度：0 → -1
    wave[2*quarter:3*quarter] = np.linspace(0, -1, quarter, endpoint=False)

    # 第四季度：-1 → 0
    wave[3*quarter:] = np.linspace(-1, 0, quarter, endpoint=False)

    # 量化到 ±8192
    quantized = np.round(wave * SAMPLE_MAX).astype(np.int16)

    # 确保关键点精确
    quantized[0] = 0
    quantized[WAVETABLE_SIZE // 4] = SAMPLE_MAX      # 8192
    quantized[WAVETABLE_SIZE // 2] = 0               # 0
    quantized[3 * WAVETABLE_SIZE // 4] = SAMPLE_MIN  # -8192

    return quantized


def analyze_harmonic_content(wavetable: np.ndarray, num_harmonics: int = 10) -> dict:
    """分析波表的谐波成分

    Args:
        wavetable: 波表样本
        num_harmonics: 分析的谐波数量

    Returns:
        谐波分析结果字典
    """
    # FFT 分析
    spectrum = np.fft.fft(wavetable.astype(float))
    magnitude = np.abs(spectrum[:WAVETABLE_SIZE // 2])

    # 归一化到基波
    fundamental = magnitude[1]
    if fundamental > 0:
        normalized = magnitude / fundamental
    else:
        normalized = magnitude

    # 提取前 N 个谐波
    harmonics = {}
    for n in range(1, min(num_harmonics + 1, len(normalized))):
        harmonics[n] = {
            'magnitude': magnitude[n],
            'normalized': normalized[n],
            'db': 20 * np.log10(normalized[n]) if normalized[n] > 1e-10 else -100
        }

    return {
        'fundamental_magnitude': fundamental,
        'harmonics': harmonics,
        'thd': np.sqrt(np.sum(magnitude[2:num_harmonics+1]**2)) / fundamental if fundamental > 0 else 0
    }


def generate_rom_hex(wavetable: np.ndarray, name: str) -> str:
    """生成 Verilog $readmemh 格式的 ROM 文件

    Args:
        wavetable: 波表样本
        name: 波表名称

    Returns:
        十六进制格式字符串
    """
    lines = [f"// {name} wavetable - 1024 samples, 16-bit signed"]
    lines.append(f"// Generated by t027_timbre_model.py")
    lines.append("")

    for i, sample in enumerate(wavetable):
        # 转换为无符号 16 位十六进制
        unsigned = int(sample) & 0xFFFF
        lines.append(f"{unsigned:04x}")

    return "\n".join(lines) + "\n"


def verify_timbre_difference() -> bool:
    """验证两种音色的谐波差异

    Returns:
        True 如果差异明显
    """
    sine = generate_sine_wavetable()
    triangle = generate_triangle_wavetable()

    sine_analysis = analyze_harmonic_content(sine)
    triangle_analysis = analyze_harmonic_content(triangle)

    print("=" * 70)
    print("音色谐波分析")
    print("=" * 70)

    print("\n正弦波（Sine）:")
    print(f"  基波幅度: {sine_analysis['fundamental_magnitude']:.1f}")
    print(f"  THD: {sine_analysis['thd']*100:.2f}%")
    print("  前 5 个谐波:")
    for n in range(1, 6):
        h = sine_analysis['harmonics'].get(n, {})
        print(f"    {n}: {h.get('normalized', 0):.4f} ({h.get('db', -100):.1f} dB)")

    print("\n三角波（Triangle）:")
    print(f"  基波幅度: {triangle_analysis['fundamental_magnitude']:.1f}")
    print(f"  THD: {triangle_analysis['thd']*100:.2f}%")
    print("  前 5 个谐波:")
    for n in range(1, 6):
        h = triangle_analysis['harmonics'].get(n, {})
        print(f"    {n}: {h.get('normalized', 0):.4f} ({h.get('db', -100):.1f} dB)")

    # 判断差异是否明显
    # 三角波应该有明显的奇次谐波
    triangle_3rd = triangle_analysis['harmonics'].get(3, {}).get('normalized', 0)
    sine_3rd = sine_analysis['harmonics'].get(3, {}).get('normalized', 0)

    diff_obvious = triangle_3rd > sine_3rd * 10  # 三角波的 3 次谐波应该明显大于正弦波

    print(f"\n差异判定: {'明显' if diff_obvious else '不明显'}")
    print(f"  三角波 3 次谐波 / 正弦波 3 次谐波 = {triangle_3rd / sine_3rd:.1f}x")

    return diff_obvious


if __name__ == "__main__":
    # 生成波表
    sine = generate_sine_wavetable()
    triangle = generate_triangle_wavetable()

    # 验证谐波差异
    if verify_timbre_difference():
        print("\n✓ 两种音色具有明确的谐波差异")
    else:
        print("\n✗ 音色差异不明显")

    # 生成 ROM 文件
    sine_hex = generate_rom_hex(sine, "Sine")
    triangle_hex = generate_rom_hex(triangle, "Triangle")

    print("\n生成的 ROM 文件已准备就绪")
    print(f"  正弦波：{len(sine_hex)} 字节")
    print(f"  三角波：{len(triangle_hex)} 字节")
