"""Generate repeatable sine ROM and RTL constants; outputs only source/rom, source/rtl."""
from pathlib import Path
import hashlib
import math
from v3_parameters import bass_coefficients, coefficient_box_bound, DECAY_SHIFTS

ROOT = Path(__file__).resolve().parents[1]

def generate():
    rom = ROOT / "rom" / "sine_v3_1024_32767.mem"
    words = [round(32767 * math.sin(2*math.pi*n/1024)) for n in range(1024)]
    rom.write_text("".join(f"{x & 65535:04x}\n" for x in words), encoding="ascii", newline="\n")
    initial, floor = bass_coefficients()
    minimum, maximum = coefficient_box_bound(initial, floor)
    assert minimum>=-8192 and maximum<=8191
    assert all(0 < b <= a for a, b in zip(initial, floor))
    lines = ["// Generated by source/model/generate_v3_assets.py; amplitudes in signed-sample units.\n"]
    for name, values, width in (("BASS_INITIAL", initial, 16), ("BASS_FLOOR", floor, 16),
                                ("PARTIAL_SHIFT", DECAY_SHIFTS, 5)):
        words = ", ".join(f"{width}'d{x}" for x in reversed(values))
        lines.append(f"localparam logic [{12*width-1}:0] {name} = {{{words}}};\n")
    constants = ROOT / "rtl" / "v3_constants.svh"
    constants.write_text("".join(lines), encoding="ascii", newline="\n")
    return {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in (rom, constants)}

if __name__ == "__main__":
    print(generate())
